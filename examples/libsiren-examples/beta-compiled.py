from siren.libsiren import *

def program(particle):
  rv1 = new_rv(particle)
  set_distr(particle, rv1, beta(const(1.0), const(1.0)))
  xt = rv1
  rv3 = new_rv(particle)
  set_distr(particle, rv3, bernoulli(xt))
  set_distr(particle, rv3, bernoulli(get_distr(particle, rv3)))
  set_distr(particle, rv3, bernoulli(get_distr(particle, rv3)))
  set_distr(particle, get_par(particle, rv3, const(0)), Beta(add(get_distr(particle, get_par(particle, rv3, const(0))), (const(1.0) if rv3 else const(0.0))), add(get_distr(particle, get_par(particle, rv3, const(0))), (const(0.0) if rv3 else const(1.0)))))
  set_distr(particle, rv3, Bernoulli(const(0.5)))
  observe_inner(particle, rv3, const(False))
  rv5 = new_rv(particle)
  set_distr(particle, rv5, bernoulli(xt))
  set_distr(particle, rv5, bernoulli(get_distr(particle, rv5)))
  set_distr(particle, rv5, bernoulli(get_distr(particle, rv5)))
  set_distr(particle, get_par(particle, rv5, const(0)), Beta(add(get_distr(particle, get_par(particle, rv5, const(0))), (const(1.0) if rv5 else const(0.0))), add(get_distr(particle, get_par(particle, rv5, const(0))), (const(0.0) if rv5 else const(1.0)))))
  set_distr(particle, rv5, Bernoulli(const(0.3333333333333333)))
  observe_inner(particle, rv5, const(True))
  rv7 = new_rv(particle)
  set_distr(particle, rv7, bernoulli(xt))
  set_distr(particle, rv7, bernoulli(get_distr(particle, rv7)))
  set_distr(particle, rv7, bernoulli(get_distr(particle, rv7)))
  set_distr(particle, get_par(particle, rv7, const(0)), Beta(add(get_distr(particle, get_par(particle, rv7, const(0))), (const(1.0) if rv7 else const(0.0))), add(get_distr(particle, get_par(particle, rv7, const(0))), (const(0.0) if rv7 else const(1.0)))))
  set_distr(particle, rv7, Bernoulli(const(0.5)))
  observe_inner(particle, rv7, const(True))
  rv9 = new_rv(particle)
  set_distr(particle, rv9, bernoulli(xt))
  set_distr(particle, rv9, bernoulli(get_distr(particle, rv9)))
  set_distr(particle, rv9, bernoulli(get_distr(particle, rv9)))
  set_distr(particle, get_par(particle, rv9, const(0)), Beta(add(get_distr(particle, get_par(particle, rv9, const(0))), (const(1.0) if rv9 else const(0.0))), add(get_distr(particle, get_par(particle, rv9, const(0))), (const(0.0) if rv9 else const(1.0)))))
  set_distr(particle, rv9, Bernoulli(const(0.6)))
  observe_inner(particle, rv9, const(True))
  rv11 = new_rv(particle)
  set_distr(particle, rv11, bernoulli(xt))
  set_distr(particle, rv11, bernoulli(get_distr(particle, rv11)))
  set_distr(particle, rv11, bernoulli(get_distr(particle, rv11)))
  set_distr(particle, get_par(particle, rv11, const(0)), Beta(add(get_distr(particle, get_par(particle, rv11, const(0))), (const(1.0) if rv11 else const(0.0))), add(get_distr(particle, get_par(particle, rv11, const(0))), (const(0.0) if rv11 else const(1.0)))))
  set_distr(particle, rv11, Bernoulli(const(0.6666666666666666)))
  observe_inner(particle, rv11, const(True))
  rv13 = new_rv(particle)
  set_distr(particle, rv13, bernoulli(xt))
  set_distr(particle, rv13, bernoulli(get_distr(particle, rv13)))
  set_distr(particle, rv13, bernoulli(get_distr(particle, rv13)))
  set_distr(particle, get_par(particle, rv13, const(0)), Beta(add(get_distr(particle, get_par(particle, rv13, const(0))), (const(1.0) if rv13 else const(0.0))), add(get_distr(particle, get_par(particle, rv13, const(0))), (const(0.0) if rv13 else const(1.0)))))
  set_distr(particle, rv13, Bernoulli(const(0.7142857142857143)))
  observe_inner(particle, rv13, const(True))
  rv15 = new_rv(particle)
  set_distr(particle, rv15, bernoulli(xt))
  set_distr(particle, rv15, bernoulli(get_distr(particle, rv15)))
  set_distr(particle, rv15, bernoulli(get_distr(particle, rv15)))
  set_distr(particle, get_par(particle, rv15, const(0)), Beta(add(get_distr(particle, get_par(particle, rv15, const(0))), (const(1.0) if rv15 else const(0.0))), add(get_distr(particle, get_par(particle, rv15, const(0))), (const(0.0) if rv15 else const(1.0)))))
  set_distr(particle, rv15, Bernoulli(const(0.75)))
  observe_inner(particle, rv15, const(True))
  rv17 = new_rv(particle)
  set_distr(particle, rv17, bernoulli(xt))
  set_distr(particle, rv17, bernoulli(get_distr(particle, rv17)))
  set_distr(particle, rv17, bernoulli(get_distr(particle, rv17)))
  set_distr(particle, get_par(particle, rv17, const(0)), Beta(add(get_distr(particle, get_par(particle, rv17, const(0))), (const(1.0) if rv17 else const(0.0))), add(get_distr(particle, get_par(particle, rv17, const(0))), (const(0.0) if rv17 else const(1.0)))))
  set_distr(particle, rv17, Bernoulli(const(0.7777777777777778)))
  observe_inner(particle, rv17, const(True))
  particle.finished = True
  return xt

run(program, 1000)
