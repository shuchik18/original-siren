HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]


def local_path(value):
    path = (HERE / value).resolve()
    if not path.is_relative_to(HERE):
        raise ValueError(f"Output must stay inside {HERE}: {path}")
    return path


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def revision(path):
    p = subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"],
                       capture_output=True, text=True)
    return p.stdout.strip() if p.returncode == 0 else None


def compiler_environment():
    env = dict(os.environ)
    temp = local_path("_build/tmp")
    temp.mkdir(parents=True, exist_ok=True)
    env.update(TMPDIR=str(temp), TMP=str(temp), TEMP=str(temp),
               PYTHONDONTWRITEBYTECODE="1")
    # Prefer the user's configured switch; otherwise locate the installed one.
    if not shutil.which("ocamlfind", path=env.get("PATH")):
        candidates = [Path.home() / ".opam/miking-ocaml/bin"]
        candidates += sorted((Path.home() / ".opam").glob("*/bin"))
        found = next((p for p in candidates if (p / "ocamlfind").is_file()), None)
        if found:
            env["PATH"] = str(found) + os.pathsep + env.get("PATH", "")
    if not shutil.which("ocamlfind", path=env.get("PATH")):
        raise RuntimeError("ocamlfind not found. Activate your Miking/Owl OCaml switch.")
    libs = [p for p in env.get("MCORE_LIBS", "").split(":")
            if p and not p.startswith("coreppl=")]
    libs.append("coreppl=" + str(REPO / "coreppl/src"))
    env["MCORE_LIBS"] = ":".join(libs)
    return env


def wrapper_source(name, method, transformed_body=None):
    source = (HERE / f"{name}.dppl").read_text()
    declarations, body = source.split("\nmexpr\n", 1)
    posterior = transformed_body is not None
    if posterior:
        # The printed extracted model is self-contained. Do not include the
        # original declarations again or apply static DS a second time.
        declarations, body = "", transformed_body
    config = ('Importance {particles = particles, cps = "none"}' if method == "is-lw"
              else 'BPF {particles = particles, resample = "likelihood", cps = "full"}')
    flatten = 'lam x. concat x.0 x.1' if name == "wheels" else 'lam x. [x]'
    if name == "slam":
        flatten = 'lam x. concat (map (lam cell. if cell then 1.0 else 0.0) x.0) (map int2float x.1)'
    reporting = f'''let samples = map ({flatten}) result.0 in
  report elapsed (distEmpiricalNormConst dist) samples result.1;'''
    if posterior:
        reporting = '''let means = map (lam x. [x.0]) result.0 in
  let variances = map (lam x. [x.1]) result.0 in
  reportMoments elapsed (distEmpiricalNormConst dist) means variances result.1;'''
    return f'''-- Generated by benchmark.py from {name}.dppl. Loops are retained.
include "{HERE / 'benchmark-runtime.mc'}"
include "seq.mc"
include "string.mc"
include "ext/dist-ext.mc"
include "ext/math-ext.mc"
{declarations}

let benchmarkModel = lam.
{body}

mexpr
let particles = string2int (get argv 1) in
let firstSeed = string2int (get argv 2) in
let repetitions = string2int (get argv 3) in
recursive let run = lam i.
  if geqi i repetitions then () else
  setSeed (addi firstSeed i);
  let start = wallTimeMs () in
  let dist = infer ({config}) benchmarkModel in
  let elapsed = subf (wallTimeMs ()) start in
  let result = distEmpiricalSamples dist in
  {reporting}
  run (addi i 1)
in run 0
'''


def build(name, method, mode, cppl, env, timeout, readout="posterior"):
    directory = local_path(f"_build/{method}-{mode}-{readout}/{name}")
    directory.mkdir(parents=True, exist_ok=True)
    wrapper = directory / "benchmark.dppl"
    wrapper.write_text(wrapper_source(name, method))
    binary = directory / "baseline"
    command = [str(cppl), str(wrapper), "--extract-simplification", "inline",
               "--print-model", "--output", str(binary)]
    if mode == "static":
        command.append("--static-delay")
    start = time.perf_counter()
    try:
        completed = subprocess.run(command, cwd=directory, env=env, text=True,
                                   capture_output=True, timeout=timeout)
        stdout, stderr, returncode = completed.stdout, completed.stderr, completed.returncode
        status = "compile_error" if returncode else "ok"
    except subprocess.TimeoutExpired as exc:
        stdout = (exc.stdout or b"").decode(errors="replace") if isinstance(exc.stdout, bytes) else exc.stdout or ""
        stderr, returncode, status = str(exc), None, "compile_timeout"
    elapsed = time.perf_counter() - start
    (directory / "compile.stderr").write_text(stderr)
    (directory / "compile.stdout").write_text(stdout)
    info = {"model": name, "method": method, "mode": mode, "command": command,
            "seconds": elapsed, "returncode": returncode,
            "log_directory": str(directory.relative_to(HERE))}
    if status != "ok":
        return None, {**info, "status": status, "error": (stderr + stdout)[-4000:]}
    snapshot = local_path(f"transformed/{method}-{mode}/{name}.txt")
    snapshot.parent.mkdir(parents=True, exist_ok=True)
    snapshot.write_text(stdout)
    # Check loop retention and that observation sites were not copied.
    observe_sites = len(re.findall(r"\bobserve\b", stdout))
    retained_loop = "foldl" in stdout or bool(re.search(r"\brecursive\s+let rec", stdout))
    loop_observations = {"kalman": 1, "wheels": 2, "outlier": 2, "slam": 1}
    if name in loop_observations:
        if not retained_loop or observe_sites != loop_observations[name]:
            raise RuntimeError(f"Loop/observation-site audit failed in {snapshot}")
    info = {**info, "status": "ok", "requested_readout": readout, "readout": "samples",
                    "binary_sha256": digest(binary), "snapshot": str(snapshot.relative_to(HERE)),
                    "snapshot_sha256": digest(snapshot), "observe_sites": observe_sites,
                    "retained_loop": retained_loop,
                    "assume_sites": len(re.findall(r"\bassume\b", stdout))}
    adapted, audit = (None, {"applied": False, "reason": "sample readout requested or static DS disabled"})
    if readout == "posterior" and mode == "static":
        adapted, audit = adapt_posterior_readout(stdout)
    info["readout_audit"] = audit
    if adapted is None:
        return binary, info
    adapted_model = directory / "posterior-model.dppl"
    adapted_model.write_text("mexpr\n" + adapted)
    adapted_wrapper = directory / "posterior-benchmark.dppl"
    adapted_wrapper.write_text(wrapper_source(name, method, transformed_body=adapted))
    output = directory / "run"
    command = [str(cppl), str(adapted_wrapper), "--extract-simplification", "inline", "--output", str(output)]
    info.update(readout_model=str(adapted_model.relative_to(HERE)), readout_model_sha256=digest(adapted_model),
                readout_command=command)
    start = time.perf_counter()
    try:
        completed = subprocess.run(command, cwd=directory, env=env, text=True, capture_output=True, timeout=timeout)
        stdout, stderr, returncode = completed.stdout, completed.stderr, completed.returncode
        status = "readout_compile_error" if returncode else "ok"
    except subprocess.TimeoutExpired as exc:
        stdout, stderr, returncode, status = "", str(exc), None, "readout_compile_timeout"
    info["readout_compile_seconds"] = time.perf_counter() - start
    (directory / "readout-compile.stdout").write_text(stdout)
    (directory / "readout-compile.stderr").write_text(stderr)
    if status != "ok":
        return None, {**info, "status": status, "returncode": returncode, "error": (stderr + stdout)[-4000:]}
    info.update(readout="posterior", baseline_binary_sha256=info["binary_sha256"], binary_sha256=digest(output))
    return output, info


def error_metrics(mean, variance, log_z, truth):
    if len(mean) != len(truth["mean"]):
        raise ValueError("Incorrect output dimension")
    d = len(mean)
    differences = [x - y for x, y in zip(mean, truth["mean"])]
    result = {
        "mean_rmse": math.sqrt(sum(x * x for x in differences) / d),
        "mean_standardized_rmse": math.sqrt(sum(x * x / v for x, v in
                                                zip(differences, truth["variance"])) / d),
        "mean_max_abs_error": max(map(abs, differences)),
        "log_z_abs_error": abs(log_z - truth["log_z"]) if log_z is not None else None,
    }
    if variance is not None:
        if len(variance) != d:
            raise ValueError("Incorrect variance dimension")
        result["variance_rmse"] = math.sqrt(sum((x - y) ** 2 for x, y in
                                               zip(variance, truth["variance"])) / d)
    else:
        result["variance_rmse"] = None
    return result


def parse_coreppl(stdout, dimensions, count):
    lines = stdout.strip().splitlines()
    if len(lines) != 3 * count:
        raise ValueError(f"Expected {3 * count} output lines, got {len(lines)}")
    results = []
    for i in range(count):
        header, mean, variance = [[parse_float(token) for token in s.split()] for s in lines[3*i:3*i+3]]
        if len(header) != 4 or len(mean) != dimensions or len(variance) != dimensions:
            raise ValueError("Malformed CorePPL summary")
        if not all(math.isfinite(x) for x in header + mean + variance):
            raise ValueError("Non-finite CorePPL result (possibly degenerate weights)")
        elapsed_ms, summary_ms, log_z, ess = header
        if elapsed_ms < 0 or summary_ms < 0:
            raise ValueError("Wall clock moved backwards during measurement")
        results.append({"inference_seconds": elapsed_ms / 1000,
                        "summary_seconds": summary_ms / 1000,
                        "log_z": log_z, "ess": ess, "mean": mean, "variance": variance})
    return results


def parse_float(token):
    """Read both legacy decimal tokens and lossless high:residual tokens."""
    parts = token.split(":")
    if len(parts) not in (1, 2):
        raise ValueError("Malformed floating-point token")
    return sum(map(float, parts))


def summarize(rows):
    groups = {}
    for row in rows:
        readout = row.get("readout", "symbolic" if row["engine"] == "siren" else "samples")
        key = tuple(row[k] for k in ("engine", "model", "method", "mode", "particles")) + (readout,)
        groups.setdefault(key, []).append(row)
    result = []
    for key, group in groups.items():
        record = dict(zip(("engine", "model", "method", "mode", "particles", "readout"), key))
        record["requested_readout"] = next((r.get("requested_readout") for r in group
                                            if r.get("requested_readout")), None)
        record["known_issue"] = next((r["known_issue"] for r in group if r.get("known_issue")), None)
        valid = [r for r in group if r["status"] == "ok"]
        record.update(runs=len(group), successful_runs=len(valid))
        for metric in ("inference_seconds", "summary_seconds", "mean_rmse",
                       "mean_standardized_rmse", "variance_rmse", "log_z_abs_error", "ess"):
            values = [r[metric] for r in valid if r.get(metric) is not None]
            record[metric + "_median"] = statistics.median(values) if values else None
        # Aggregate squared error across repetitions, rather than averaging RMSEs.
        for metric in ("mean_rmse", "mean_standardized_rmse", "variance_rmse", "log_z_abs_error"):
            values = [r[metric] for r in valid if r.get(metric) is not None]
            record[metric + "_rms"] = math.sqrt(statistics.fmean(v*v for v in values)) if values else None
        result.append(record)
    return result


def write_csv(path, rows):
    if not rows:
        return
    fields = list(dict.fromkeys(k for row in rows for k in row))
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: json.dumps(v) if isinstance(v, (list, dict)) else v
                             for k, v in row.items()})


def positive(value):
    n = int(value)
    if n <= 0:
        raise argparse.ArgumentTypeError("must be positive")
    return n


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models", nargs="+", choices=MODELS, default=list(MODELS))
    parser.add_argument("--particles", nargs="+", type=positive, default=[1, 10, 100, 1000, 10000])
    parser.add_argument("--repeats", type=positive, default=5)
    parser.add_argument("--warmups", type=int, default=1)
    parser.add_argument("--methods", nargs="+", choices=["is-lw", "smc-bpf"], default=["is-lw"],
                        help="is-lw matches Siren here; optional smc-bpf has known loop runtime failures")
    parser.add_argument("--modes", nargs="+", choices=["static", "plain"], default=["static"])
    parser.add_argument("--readout", choices=["posterior", "samples"], default="posterior",
                        help="use terminal compiler-generated posterior moments when safe; samples reproduces the original readout")
    parser.add_argument("--engines", nargs="+", choices=["coreppl", "siren"], default=["coreppl"])
    parser.add_argument("--cppl", type=Path, default=REPO / "build/cppl")
    parser.add_argument("--output", default="results/" + datetime.now().strftime("%Y%m%d-%H%M%S"))
    parser.add_argument("--timeout", type=positive, default=300, help="seconds per build or particle-count batch")
    parser.add_argument("--siren-repo", type=Path,
                        default=Path.home() / "projects/psg-siren/sirenv2/siren")
    parser.add_argument("--siren-python", type=Path,
                        default=Path.home() / "projects/psg-siren/venv/bin/python")
    parser.add_argument("--siren-methods", nargs="+", choices=["ssi", "ds", "bp"], default=["ssi"])
    parser.add_argument("--fix-wheels-input", action="store_true",
                        help="apply the missing preprocess_data map in a generated local Siren copy")
    args = parser.parse_args()
    if args.warmups < 0:
        parser.error("--warmups must be nonnegative")
    output = local_path(args.output)
    if output.exists() and any(output.iterdir()):
        parser.error(f"Output directory is not empty: {output}")
    output.mkdir(parents=True, exist_ok=True)
    raw = output / "raw"
    raw.mkdir()
    env = compiler_environment() if "coreppl" in args.engines else dict(os.environ)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    temp = local_path("_build/tmp")
    temp.mkdir(parents=True, exist_ok=True)
    env.update(TMPDIR=str(temp), TMP=str(temp), TEMP=str(temp))
    truths = {name: reference(name) for name in args.models}
    (output / "reference.json").write_text(json.dumps(truths, indent=2) + "\n")
    metadata = {"created_utc": datetime.now(timezone.utc).isoformat(),
                "arguments": {k: str(v) if isinstance(v, Path) else v for k, v in vars(args).items()},
                "platform": platform.platform(), "python": sys.version, "repo_revision": revision(REPO),
                "source_sha256": {p.name: digest(p) for p in HERE.iterdir()
                                  if p.suffix in (".si", ".dppl", ".mc", ".py")},
                "builds": [], "seed_policy": "random base seed for CorePPL; OS-seeded independent Siren particle RNGs",
                "timing": "CorePPL inference includes conditional readout when used, excludes mixture aggregation/printing; Siren SMC.infer includes symbolic result mean"}
    rows = []

    def save():
        (output / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
        write_csv(output / "runs.csv", rows)
        write_csv(output / "summary.csv", summarize(rows))

    def record(row):
        rows.append(row)
        with (output / "runs.jsonl").open("a") as f:
            f.write(json.dumps(row, allow_nan=False) + "\n")

    if "coreppl" in args.engines:
        cppl = args.cppl.expanduser().resolve()
        metadata.update(cppl=str(cppl), cppl_sha256=digest(cppl), mcore_libs=env["MCORE_LIBS"])
        for name in args.models:
            for method in args.methods:
                for mode in args.modes:
                    print(f"Building {name}: {method}/{mode}", flush=True)
                    binary, info = build(name, method, mode, cppl, env, args.timeout, args.readout)
                    metadata["builds"].append(info)
                    if binary is None:
                        record({"engine": "coreppl", "model": name, "method": method, "mode": mode,
                                "requested_readout": args.readout, "readout": info.get("readout"),
                                "particles": None, "repeat": None, **{k: info[k] for k in ("status", "error", "returncode")}})
                        save()
                        continue
                    saved_snapshot = output / "transformed" / f"{name}-{method}-{mode}.txt"
                    saved_snapshot.parent.mkdir(exist_ok=True)
                    shutil.copyfile(HERE / info["snapshot"], saved_snapshot)
                    if info.get("readout_model"):
                        shutil.copyfile(HERE / info["readout_model"],
                                        saved_snapshot.with_name(saved_snapshot.stem + "-posterior.dppl"))
                    save()
                    for n in args.particles:
                        seed = secrets.randbelow(2**30 - args.repeats - args.warmups)
                        count = args.repeats + args.warmups
                        command = [str(binary), str(n), str(seed), str(count)]
                        start = time.perf_counter()
                        failure = None
                        try:
                            p = subprocess.run(command, cwd=binary.parent, env=env, text=True,
                                               capture_output=True, timeout=args.timeout)
                            stdout, stderr = p.stdout, p.stderr
                            if p.returncode:
                                failure = {"status": "runtime_error", "returncode": p.returncode,
                                           "error": f"Exited with code {p.returncode}: {stderr[-2000:]}"}
                            else:
                                results = parse_coreppl(stdout, len(truths[name]["mean"]), count)
                        except subprocess.TimeoutExpired as exc:
                            stdout = (exc.stdout or b"").decode(errors="replace") if isinstance(exc.stdout, bytes) else exc.stdout or ""
                            stderr = str(exc)
                            failure = {"status": "timeout", "error": str(exc)}
                        except ValueError as exc:
                            failure = {"status": "invalid_output", "error": str(exc)}
                        wall = time.perf_counter() - start
                        prefix = raw / f"coreppl-{name}-{method}-{mode}-{n}"
                        prefix.with_suffix(".stdout").write_text(stdout)
                        prefix.with_suffix(".stderr").write_text(stderr)
                        if failure:
                            record({"engine": "coreppl", "model": name, "method": method, "mode": mode,
                                    "requested_readout": args.readout, "readout": info["readout"],
                                    "particles": n, "repeat": None, "seed": seed,
                                    "batch_process_seconds": wall, **failure})
                            save()
                            print(f"  N={n}: {failure['status']} (see raw logs)", flush=True)
                            continue
                        for i, result in enumerate(results[args.warmups:]):
                            record({"engine": "coreppl", "model": name, "method": method, "mode": mode,
                                    "particles": n, "repeat": i, "seed": seed + args.warmups + i,
                                    "status": "ok", "readout": info["readout"], "requested_readout": args.readout,
                                    "estimator": "weighted conditional posterior moments" if info["readout"] == "posterior" else "exact mean of weighted point-mass particles; compiler retained no supported output distribution",
                                    "known_issue": "gtree_static_posterior_bias" if name == "gtree" and mode == "static" else None,
                                    "batch_process_seconds": wall, "batch_runs_including_warmup": count,
                                    **result, **error_metrics(result["mean"], result["variance"], result["log_z"], truths[name])})
                        print(f"  N={n}: mean RMSE={rows[-1]['mean_rmse']:.5g}, "
                              f"inference={rows[-1]['inference_seconds']:.6g}s", flush=True)
                        save()
    if "siren" in args.engines:
        siren_repo = args.siren_repo.expanduser().resolve()
        metadata.update(siren_repo=str(siren_repo), siren_revision=revision(siren_repo))
        for name in args.models:
            for method in args.siren_methods:
                for n in args.particles:
                    print(f"Siren {name}: {method}, N={n}", flush=True)
                    command = [str(args.siren_python.expanduser().absolute()), "-B", str(HERE / "siren_adapter.py"),
                               "--repo", str(siren_repo), "--model", name, "--method", method,
                               "--particles", str(n), "--repeats", str(args.repeats + args.warmups)]
                    if args.fix_wheels_input:
                        command.append("--fix-wheels-input")
                    start = time.perf_counter()
                    stdout, stderr = "", ""
                    try:
                        p = subprocess.run(command, cwd=HERE, env=env, capture_output=True,
                                           text=True, timeout=args.timeout)
                        stdout, stderr = p.stdout, p.stderr
                        if p.returncode:
                            raise RuntimeError(stderr[-2000:])
                        results = [json.loads(line) for line in stdout.splitlines()]
                        if len(results) != args.repeats + args.warmups:
                            raise ValueError("Wrong number of Siren results")
                    except subprocess.TimeoutExpired as exc:
                        stdout = (exc.stdout or b"").decode(errors="replace") if isinstance(exc.stdout, bytes) else exc.stdout or ""
                        stderr = str(exc)
                        results = [{"status": "timeout", "error": str(exc)}] * (args.repeats + args.warmups)
                    except (RuntimeError, ValueError) as exc:
                        stderr = stderr or str(exc)
                        results = [{"status": "error", "error": str(exc)}] * (args.repeats + args.warmups)
                    wall = time.perf_counter() - start
                    prefix = raw / f"siren-{name}-{method}-{n}"
                    prefix.with_suffix(".stdout").write_text(stdout)
                    prefix.with_suffix(".stderr").write_text(stderr)
                    for i, result in enumerate(results[args.warmups:]):
                        if result["status"] == "ok":
                            result.update(error_metrics(result["mean"], None, result["log_z"], truths[name]))
                        record({"engine": "siren", "model": name, "method": "smc-" + method,
                                "mode": "runtime-symbolic", "particles": n, "repeat": i, "seed": None,
                                "estimator": "symbolic mixture mean", "batch_process_seconds": wall,
                                "batch_runs_including_warmup": args.repeats + args.warmups, **result})
                    save()
    save()
    print(f"Results: {output}")
    if any(row["status"] != "ok" for row in rows):
        print("Some experiments failed; see status/error fields in runs.csv.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.dont_write_bytecode = True
    try:
        sys.exit(main())
    except (ValueError, RuntimeError, OSError, subprocess.TimeoutExpired) as exc:
        sys.exit(str(exc))
