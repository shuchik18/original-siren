from siren.libsiren import *

def program(particle):
  rv1 = new_rv(particle)
  set_distr(particle, rv1, beta(const(1.0), const(1.0)))
  xt = rv1
  rv3 = new_rv(particle)
  set_distr(particle, rv3, bernoulli(xt))
  set_distr(particle, rv3, bernoulli(xt))
  __siren_update_posterior_5 = Beta(add(get_a(get_distr(particle, get_par(particle, rv3, const(0)))), (const(1.0) if rv3 else const(0.0))), add(get_b(get_distr(particle, get_par(particle, rv3, const(0)))), (const(0.0) if rv3 else const(1.0))))
  set_distr(particle, get_par(particle, rv3, const(0)), __siren_update_posterior_5)
  set_distr(particle, rv3, bernoulli(const(0.5)))
  set_distr(particle, rv3, bernoulli(const(0.5)))
  observe_inner(particle, rv3, const(False))
  rv6 = new_rv(particle)
  set_distr(particle, rv6, bernoulli(xt))
  set_distr(particle, rv6, bernoulli(get_p(get_distr(particle, rv6))))
  set_distr(particle, rv6, bernoulli(get_p(get_distr(particle, rv6))))
  observe_inner(particle, rv6, const(True))
  rv9 = new_rv(particle)
  set_distr(particle, rv9, bernoulli(xt))
  set_distr(particle, rv9, bernoulli(get_p(get_distr(particle, rv9))))
  set_distr(particle, rv9, bernoulli(get_p(get_distr(particle, rv9))))
  observe_inner(particle, rv9, const(True))
  rv11 = new_rv(particle)
  set_distr(particle, rv11, bernoulli(xt))
  set_distr(particle, rv11, bernoulli(get_p(get_distr(particle, rv11))))
  set_distr(particle, rv11, bernoulli(get_p(get_distr(particle, rv11))))
  observe_inner(particle, rv11, const(True))
  rv13 = new_rv(particle)
  set_distr(particle, rv13, bernoulli(xt))
  set_distr(particle, rv13, bernoulli(get_p(get_distr(particle, rv13))))
  set_distr(particle, rv13, bernoulli(get_p(get_distr(particle, rv13))))
  observe_inner(particle, rv13, const(True))
  rv15 = new_rv(particle)
  set_distr(particle, rv15, bernoulli(xt))
  set_distr(particle, rv15, bernoulli(get_p(get_distr(particle, rv15))))
  set_distr(particle, rv15, bernoulli(get_p(get_distr(particle, rv15))))
  observe_inner(particle, rv15, const(True))
  rv17 = new_rv(particle)
  set_distr(particle, rv17, bernoulli(xt))
  set_distr(particle, rv17, bernoulli(get_p(get_distr(particle, rv17))))
  set_distr(particle, rv17, bernoulli(get_p(get_distr(particle, rv17))))
  observe_inner(particle, rv17, const(True))
  rv19 = new_rv(particle)
  set_distr(particle, rv19, bernoulli(xt))
  set_distr(particle, rv19, bernoulli(get_p(get_distr(particle, rv19))))
  set_distr(particle, rv19, bernoulli(get_p(get_distr(particle, rv19))))
  observe_inner(particle, rv19, const(True))
  particle.finished = True
  return xt

run(program, 1000)
