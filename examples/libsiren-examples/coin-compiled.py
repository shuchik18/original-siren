from siren.libsiren import *

def program(particle):
  rv1 = new_rv(particle)
  set_distr(particle, rv1, beta(const(1.0), const(1.0)))
  xt = rv1
  rv3 = new_rv(particle)
  set_distr(particle, rv3, bernoulli(xt))
  set_distr(particle, rv3, bernoulli(xt))
  set_distr(particle, get_par(particle, rv3, const(0)), Beta(add(get_a(get_distr(particle, get_par(particle, rv3, const(0)))), ifelse(rv3, const(1.0), const(0.0))), add(get_b(get_distr(particle, get_par(particle, rv3, const(0)))), ifelse(rv3, const(0.0), const(1.0)))))
  set_distr(particle, rv3, bernoulli(const(0.5)))
  set_distr(particle, rv3, bernoulli(const(0.5)))
  observe_inner(particle, rv3, const(False))
  rv5 = new_rv(particle)
  set_distr(particle, rv5, bernoulli(xt))
  set_distr(particle, rv5, bernoulli(get_p(get_distr(particle, rv5))))
  set_distr(particle, rv5, bernoulli(get_p(get_distr(particle, rv5))))
  observe_inner(particle, rv5, const(True))
  rv8 = new_rv(particle)
  set_distr(particle, rv8, bernoulli(xt))
  set_distr(particle, rv8, bernoulli(get_p(get_distr(particle, rv8))))
  set_distr(particle, rv8, bernoulli(get_p(get_distr(particle, rv8))))
  observe_inner(particle, rv8, const(True))
  rv10 = new_rv(particle)
  set_distr(particle, rv10, bernoulli(xt))
  set_distr(particle, rv10, bernoulli(get_p(get_distr(particle, rv10))))
  set_distr(particle, rv10, bernoulli(get_p(get_distr(particle, rv10))))
  observe_inner(particle, rv10, const(True))
  rv12 = new_rv(particle)
  set_distr(particle, rv12, bernoulli(xt))
  set_distr(particle, rv12, bernoulli(get_p(get_distr(particle, rv12))))
  set_distr(particle, rv12, bernoulli(get_p(get_distr(particle, rv12))))
  observe_inner(particle, rv12, const(True))
  rv14 = new_rv(particle)
  set_distr(particle, rv14, bernoulli(xt))
  set_distr(particle, rv14, bernoulli(get_p(get_distr(particle, rv14))))
  set_distr(particle, rv14, bernoulli(get_p(get_distr(particle, rv14))))
  observe_inner(particle, rv14, const(True))
  rv16 = new_rv(particle)
  set_distr(particle, rv16, bernoulli(xt))
  set_distr(particle, rv16, bernoulli(get_p(get_distr(particle, rv16))))
  set_distr(particle, rv16, bernoulli(get_p(get_distr(particle, rv16))))
  observe_inner(particle, rv16, const(True))
  rv18 = new_rv(particle)
  set_distr(particle, rv18, bernoulli(xt))
  set_distr(particle, rv18, bernoulli(get_p(get_distr(particle, rv18))))
  set_distr(particle, rv18, bernoulli(get_p(get_distr(particle, rv18))))
  observe_inner(particle, rv18, const(True))
  particle.finished = True
  return xt

run(program, 1000)
